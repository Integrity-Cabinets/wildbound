#!/usr/bin/env python3
"""Write docs/DIALOG.md: every line of dialog, sign text and narration in the game, read straight
from src/game.js and src/maps.js so the catalogue cannot drift from what the player sees.

    python3 tools/dialog_catalog.py

Lines are grouped by where they live in the code (an area's people, a scene, an area's signs).
The speaker is worked out from the code around each block of lines; check it against the game if
it looks wrong."""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STR = r'(?:"(?:[^"\\]|\\.)*"|`(?:[^`\\]|\\.)*`)'
BLOCK = re.compile(r'\[\s*' + STR + r'(?:\s*,\s*' + STR + r')*\s*\]')
ONE = re.compile(STR)
SPEAKERS = {'cole': 'Cole', 'wren': 'Professor Wren', 'june': 'June'}
SECTION = [(r'function npcsHearthmoss', 'Hearthmoss Village and Route 1: people'), (r'function npcsRoute2', 'Route 2: people'),
           (r'function npcsCindervale', 'Cindervale City: people'), (r'async function talkLodge', 'Cindervale: the Rest Lodge'),
           (r'async function talkCurator', 'Cindervale: the Archive field station'), (r'async function talkJune', 'June'),
           (r'async function talkCole', 'Cole in Hearthmoss'), (r'async function talkWren', 'Professor Wren'), (r'async function wrenIntro', "Wren's introduction"),
           (r'async function starterScene', 'Choosing a starter and the first Cole battle'), (r'async function dadCall', "Dad's call"),
           (r'async function sensorScene', 'The grey patch and the first sensor'), (r'async function whiteout', 'After losing a battle'),
           (r'async function afterBattle', 'After a battle'), (r'async function checkEvos', 'Evolution'), (r'async function pickUp', 'Finding a satchel'),
           (r'function interact', 'Looking at things'), (r'function arrive', 'Walking into things'), (r'async function begin', 'The opening'),
           (r'MAPS\.hearthmoss=', 'Hearthmoss Village and Route 1: signs and objects'), (r'MAPS\.route2=', 'Route 2: signs and objects'),
           (r'MAPS\.cindervale=', 'Cindervale City: signs and objects')]


def speaker(src, i, block):
    line = src[src.rfind('\n', 0, i) + 1:i]; tail = src[max(0, i - 220):i]
    key = re.search(r'(intro|win|lose|after):\s*$', tail)
    st = max(src.rfind(k, 0, i) for k in ('addNpc(', 'amb(', 'T_(', 'addKith('))      # the statement that adds this person
    stmt = src[st:i] if 0 <= st and i - st < 1200 else line
    name = re.findall(r"name:'([^']+)'", stmt)
    if key and name: return f"{name[-1].title()} ({ {'intro': 'before the battle', 'win': 'when beaten', 'lose': 'when they win', 'after': 'afterwards'}[key.group(1)]})"
    m = re.search(r"tell\(\s*(?:'([^']+)'|(\w+))\s*,\s*(?:[^\[\]]*\?\s*)?(?:\[[^\[\]]*\]\s*:\s*)?$", tail)
    if m:
        who = m.group(1) or m.group(2)
        if who == 'N':
            n = re.findall(r"N='([^']+)'", src[:i]); who = n[-1] if n else 'N'
        return SPEAKERS.get(who, who.title() if who.isupper() or ' ' in who else who)
    if re.search(r'note\(\s*(?:[^\[\]]*\?\s*)?$', tail) or re.search(r'note\(\[[^\]]*$', tail): return 'Narration'
    if re.search(r'say\(\s*$', tail): return 'Sign or object'
    if re.search(r"sp:'\w+'", stmt) and 'lines:' in tail[-12:]: return 'A Kith (description)'
    if name: return name[-1].title()
    m = re.search(r"id:'(\w+)'", stmt)
    if m: return {'june': 'June', 'cole': 'Cole', 'wren': 'Professor Wren'}.get(m.group(1), m.group(1))
    return 'Narration' if 'talk(' in tail[-40:] else 'Sign or object'


def clean(t):
    t = t[1:-1].replace('\\"', '"').replace("\'", "'")
    t = re.sub(r'^\{(\w+)\}\s*', lambda m: f'*({m.group(1)})* ', t)
    return re.sub(r'\$\{[^}]*\}', '…', t)


def main():
    out = ['# Dialogue catalogue', '', 'Generated by `tools/dialog_catalog.py` from the game code. Do not edit by hand; edit the game and run the tool again.',
           '', '**Approval:** Derek has not signed off any dialogue line by line yet. Everything here was written in development sessions, from the Story Bible digest in `docs/HANDOFF.md`. Treat names and facts first stated here as proposals until he says yes.',
           '', 'Lines in *(brackets)* at the start of a line are the portrait expression. An ellipsis (…) stands for a name the game fills in.', '']
    total = 0
    for f in ('src/game.js', 'src/maps.js'):
        src = open(os.path.join(ROOT, f), encoding='utf-8').read()
        marks = sorted((m.start(), title) for pat, title in SECTION for m in [re.search(pat, src)] if m)
        cur = None
        for m in BLOCK.finditer(src):
            lines = [clean(x) for x in ONE.findall(m.group(0))]
            if not any(len(x) > 14 and ' ' in x for x in lines): continue
            sec = next((t for p, t in reversed(marks) if p <= m.start()), None)
            if sec is None: continue
            if sec != cur: cur = sec; out += ['', f'## {sec}', '', '| Who | Lines |', '| --- | --- |']
            out.append(f"| {speaker(src, m.start(), m.group(0))} | {'<br>'.join(x.replace('|', '/') for x in lines)} |"); total += len(lines)
    out[2] += f' {total} lines.'
    open(os.path.join(ROOT, 'docs', 'DIALOG.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('docs/DIALOG.md', total, 'lines')


main()
